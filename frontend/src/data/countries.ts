export const DEFAULT_COUNTRY_ISO = "CN";

const countryIndex = new Map(COUNTRIES.map((country) => [country.iso, country]));

const displayNamesCache = new Map<string, Intl.DisplayNames>();

export function findCountry(iso: string): Country {
  return countryIndex.get(iso) ?? countryIndex.get(DEFAULT_COUNTRY_ISO)!;
}

/** Localised region name, falling back to the ISO code. */
export function countryName(iso: string, language: string): string {
  try {
    const locale = language.startsWith("zh") ? "zh-CN" : language;
    let names = displayNamesCache.get(locale);
    if (!names) {
      names = new Intl.DisplayNames([locale], { type: "region" });
      displayNamesCache.set(locale, names);
    }
    return names.of(iso) ?? iso;
  } catch {
    return iso;
  }
}

/** Regional-indicator flag emoji; Windows WebView2 renders it as the ISO code. */
export function flagEmoji(iso: string): string {
  if (!/^[A-Z]{2}$/.test(iso)) {
    return "🌐";
  }
  return String.fromCodePoint(
    ...[...iso].map((char) => 0x1f1e6 + char.charCodeAt(0) - 65),
  );
}

export function countriesSorted(language: string): Country[] {
  return COUNTRIES.slice().sort((a, b) =>
    countryName(a.iso, language).localeCompare(countryName(b.iso, language), language),
  );
}
