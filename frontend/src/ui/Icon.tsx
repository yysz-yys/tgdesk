export interface IconProps {
  name: string;
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: CSSProperties;
  label?: string;
  /** Accepted for call-site compatibility with the Material icon wrapper. */
  filled?: boolean;
  weight?: number;
  slot?: string;
}

export function Icon({
  name,
  size = 18,
  strokeWidth = 1.8,
  className,
  style,
  label,
}: IconProps) {
  const Glyph = ICONS[name] ?? CircleHelp;
  return (
    <Glyph
      className={cn("f-icon", className)}
      size={size}
      strokeWidth={strokeWidth}
      style={style}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    />
  );
}
